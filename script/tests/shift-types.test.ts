const native=new DatabaseSync(':memory:');
const db:any={prepare:(s:string)=>native.prepare(s),exec:(s:string)=>native.exec(s),transaction:(f:any)=>()=>{native.exec('BEGIN');try{const r=f();native.exec('COMMIT');return r;}catch(e){native.exec('ROLLBACK');throw e;}}};
db.exec('CREATE TABLE shifts(id INTEGER PRIMARY KEY,work_date TEXT,position TEXT,start_time TEXT,end_time TEXT)');
initStaffAlerts(db);
const guard:any=(_q:any,_r:any,next:any)=>next();registerShiftTypes(express(),db,{admin:guard,staff:guard,owner:guard});
const legacy=structuredClone(defaultAlertConfig);legacy.weekday.Open.start='07:00';
db.prepare('UPDATE staff_alert_settings SET config=? WHERE id=1').run(JSON.stringify(legacy));
assert.equal(readShiftTypes(db).types[0].weekday.start,'07:00');
db.exec("INSERT INTO shifts VALUES(1,'2026-10-12','Open','',''),(2,'2026-10-13','Open','',''),(3,'2026-10-11','Open','10:00','12:00')");
const types=structuredClone(readShiftTypes(db).types);types[0].label='이른 아침';types[0].weekday.start='06:30';types[0].weekend.start='09:00';
types.push({...structuredClone(types[0]),id:'Extra',label:'추가 근무'});
let saved=saveShiftTypes(db,{types,version:0},1,'2026-10-13');
assert.equal(saved.version,1);
assert.equal(db.prepare('SELECT start_time FROM shifts WHERE id=1').get().start_time,'07:00');
assert.equal(db.prepare('SELECT start_time FROM shifts WHERE id=2').get().start_time,'');
assert.equal(db.prepare('SELECT start_time FROM shifts WHERE id=3').get().start_time,'10:00');
const config=readAlertState(db).config;
const hours=(day:string,startTime='')=>effectiveHours(config,{workDate:day,position:'Extra',startTime,endTime:''});
assert.equal(hours('2026-10-13')?.start,'06:30');assert.equal(hours('2026-10-17')?.start,'09:00');assert.equal(hours('2026-10-09')?.start,'09:00');assert.equal(hours('2026-10-13','10:00')?.start,'10:00');
assert.equal(config.shiftRoles?.Extra,'recipe');assert.equal(config.shiftLabels?.Open,'이른 아침');
assertShiftType(db,'Extra');assert.throws(()=>saveShiftTypes(db,{types,version:0},1),/설정이 변경/);
