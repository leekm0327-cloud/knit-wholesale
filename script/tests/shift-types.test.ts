import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import express from 'express';
import {registerShiftTypes,readShiftTypes,saveShiftTypes,assertShiftType} from '../../server/shift-types';
import {initStaffAlerts,readAlertState} from '../../server/staff-alerts';
import {effectiveHours,defaultAlertConfig} from '../../shared/staff-alerts';
